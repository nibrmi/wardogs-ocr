"""Как интерфейс WARDOGS ведёт себя на разных разрешениях (проверено на 3440×1440, 1920×1080 и 1600×900).

Интерфейс масштабируется по ВЫСОТЕ экрана: на любом разрешении после приведения кадра к высоте 1440
шрифты и вертикальные положения те же, что на 3440×1440. По ширине элементы прижаты к своему краю:
лента убийств, вкладки и инвентарь — к левому, журнал урона и экран итогов — к центру.

Поэтому кадр приводим к высоте 1440 с сохранением пропорций (не растягиваем до 3440 по ширине!),
координаты «левых» элементов берём как есть, а «центральные» сдвигаем от середины экрана.
"""
from PIL import Image

BASE_H = 1440   # высота, к которой приводим кадр
REF_W = 3440    # ширина экрана, на котором заданы координаты (центр — REF_W / 2)


def to_base(frame: Image.Image):
    """Кадр любого разрешения -> (кадр высотой 1440, масштаб k = исходная высота / 1440)."""
    k = frame.height / BASE_H
    if abs(k - 1) < 1e-3:
        return frame, 1.0
    return frame.resize((round(frame.width / k), BASE_H), Image.LANCZOS), k


def centered(box, width):
    """Прямоугольник, заданный для экрана шириной 3440 и стоящий по центру, — для экрана другой ширины."""
    dx = (width - REF_W) // 2
    x0, y0, x1, y1 = box
    return (max(0, x0 + dx), y0, min(width, x1 + dx), y1)
